const dictionaries: Record<Language, Dictionary> = {
  en: EN,
  vi: { ...EN, ...VI },
};

function interpolate(value: string, params?: TranslationParams): string {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

function makeTranslator(language: Language) {
  return (key: string, params?: TranslationParams) => interpolate(dictionaries[language][key] ?? EN[key] ?? key, params);
}

const defaultLanguageContext: LanguageContextValue = {
  language: "en",
  setLanguage: () => undefined,
  toggleLanguage: () => undefined,
  t: makeTranslator("en"),
};

export interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, params?: TranslationParams) => string;
}

export const LanguageContext = createContext<LanguageContextValue>(defaultLanguageContext);

const STORAGE_KEY = "bookaura-language";

function readInitialLanguage(): Language {
  if (typeof window === "undefined") return "vi";
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "vi";
  } catch {
    return "vi";
  }
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(readInitialLanguage);
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === "vi" ? "en" : "vi"),
    t: makeTranslator(language),
  }), [language]);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // A language preference is optional; private browsing can reject storage writes.
    }
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
